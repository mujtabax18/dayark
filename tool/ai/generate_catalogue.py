"""Regenerate the bundled Dart catalogue after updating tool/ai/dayark_model_catalog.csv."""
import csv
from datetime import date
from urllib.parse import urlparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
fields = ['variant_id', 'model_name', 'family', 'parameters_b_label', 'quantization',
          'license_id_expected', 'model_card_url', 'download_size_mb_approx',
          'min_free_ram_gib_estimate', 'recommended_desktop_total_ram_gib',
          'recommended_mobile_total_ram_gib', 'supported_native_platforms_expected',
          'mobile_recommendation', 'recommended_context_tokens', 'model_repository',
          'filename', 'revision', 'compatibility_evidence', 'notes', 'recommended_free_disk_gib', 'family_release_date', 'family_release_source_url']
rows = list(csv.DictReader((root / 'tool/ai/dayark_model_catalog.csv').open()))
# Family launch dates may have month precision when the publisher gives no day.
# Never substitute repository creation, quantization upload or model-size dates.
family_dates = {}
for row in rows:
    value = row['family_release_date']
    parsed = date.fromisoformat(value + '-01' if len(value) == 7 else value)
    assert parsed.isoformat()[:len(value)] == value, f'Invalid release date: {value}'
    source = urlparse(row['family_release_source_url'])
    assert source.scheme == 'https' and source.netloc, 'Release source must be HTTPS'
    release = (value, row['family_release_source_url'])
    assert family_dates.setdefault(row['family'], release) == release, 'Inconsistent family release data'
output = "part of 'model_catalogue.dart';\n\n// Generated by tool/ai/generate_catalogue.py. Do not edit.\n"
output += '// Columns: ' + ', '.join(fields) + '\n'
output += 'const _catalogueRows = <List<String>>[\n'
for row in rows:
    output += '  ' + json.dumps([row[f] for f in fields], ensure_ascii=False).replace('$', r'\$') + ',\n'
output += '];\n'
(root / 'lib/ai/model_manager/model_catalogue_csv.dart').write_text(output)
